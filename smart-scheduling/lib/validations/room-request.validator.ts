import { z } from "zod";

// Everything except newline, carriage return and tab (a message is free text,
// but control characters have no business in it or in the e-mail it ends up in).
const NO_CONTROL_CHARS_EXCEPT_NEWLINE = /^[^\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F]*$/;

// The fields a room request adds to a normal booking's fields (those are
// validated by createMeetingSchema). The organizer being asked, the booking in
// the way and the status are never read from the client.
export const roomRequestExtrasSchema = z.object({
  message: z
    .string()
    .trim()
    .min(1, "Please explain why you need the room")
    .max(1000, "The message can be at most 1000 characters")
    .regex(NO_CONTROL_CHARS_EXCEPT_NEWLINE, "The message contains invalid characters"),

  // Generated by the browser for each submit; a repeat returns the same request.
  client_request_id: z
    .string()
    .regex(/^[A-Za-z0-9-]{8,64}$/, "Invalid request key")
    .optional(),
});

export const roomRequestDecisionSchema = z.discriminatedUnion("action", [
  z.object({
    action: z.literal("approve"),
    // Explicitly also cancel the organizer's own booking for this date.
    release_booking: z.boolean().optional(),
  }),
  z.object({
    action: z.literal("reject"),
    reason: z
      .string()
      .trim()
      .max(500, "The reason can be at most 500 characters")
      .regex(NO_CONTROL_CHARS_EXCEPT_NEWLINE, "The reason contains invalid characters")
      .optional(),
  }),
  z.object({ action: z.literal("release") }),
  z.object({ action: z.literal("cancel") }),
]);
