// Report downloads for the booking dashboard. The same filters that drive the
// dashboard produce the file, rows are pulled from the database in batches and
// written straight to the response stream, so memory stays flat however many
// bookings match.

export type ReportFormat = "csv" | "xlsx" | "pdf";

export const REPORT_CONTENT_TYPES: Record<ReportFormat, string> = {
  csv: "text/csv; charset=utf-8",
  xlsx: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
  pdf: "application/pdf",
};

const COLUMNS = [
  "Booking ID",
  "Organizer name",
  "Organizer email",
  "Group",
  "Meeting type",
  "Priority",
  "Meeting title",
  "Room",
  "Date",
  "Start time",
  "End time",
  "Status",
  "Replaced by",
  "Replacement reason",
] as const;

// Participants are listed directly under their meeting, indented one column in
// (the first column stays empty), like the expanded row on the dashboard.
const PARTICIPANT_HEADS = [
  "Participant",
  "Email",
  "Invitation category",
  "Response",
] as const;

type ReportRow = DashboardBookingBase & {
  bumped?: BumpInfo | null;
  participants?: ParticipantRow[];
};

const RESPONSE_TEXT: Record<string, string> = {
  ACCEPTED: "Accepted",
  DECLINED: "Declined",
  NO_RESPONSE: "No Response",
};

function participantCells(p: ParticipantRow): string[] {
  return [
    `${p.name} (ID ${p.employeeId})`,
    p.email,
    invitationCategory(p.isOptional),
    RESPONSE_TEXT[p.response] ?? "No Response",
  ];
}

function cells(r: ReportRow): (string | number)[] {
  return [
    r.bookingId,
    r.organizerName,
    r.organizerEmail,
    r.groupName ?? "",
    r.meetingType,
    r.priorityAtBooking ?? "",
    r.title,
    r.roomName,
    r.meetingDate,
    formatTime(r.startTime),
    formatTime(r.endTime),
    r.status,
    r.bumped?.byName ?? "",
    r.bumped?.reason ?? "",
  ];
}

function summaryLines(
  filters: Pick<DashboardFilters, "period">,
  metrics: DashboardMetrics,
  generatedBy: string
): [string, string | number][] {
  const now = nowInAppTimezone();

  return [
    ["Report generated", `${now.date} ${formatTime(now.time)} (${APP_TIMEZONE})`],
    ["Generated by", generatedBy],
    ["Reporting period", filters.period.label],
    ["Total bookings", metrics.totalBookings],
    ["Confirmed bookings", metrics.confirmedBookings],
    ["Cancelled bookings", metrics.cancelledBookings],
    ["Replaced bookings", metrics.bumpedBookings],
    ["Pending reschedule", metrics.pendingBookings],
    ["Total meeting hours", metrics.totalMeetingHours],
    ["Active meeting rooms", metrics.activeRooms],
  ];
}

function csvCell(value: string | number) {
  const text =
    typeof value === "string" ? neutralizeFormula(value) : String(value);

  return /[",\r\n]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text;
}

const csvLine = (values: (string | number)[]) =>
  values.map(csvCell).join(",") + "\r\n";

export type ReportInput = {
  filters: Pick<DashboardFilters, "period">;
  metrics: DashboardMetrics;
  generatedBy: string;
  // Each booking carries its invited people, listed beneath it in the report.
  rows: AsyncIterable<ReportRow>;
};

async function writeCsv(
  out: PassThrough,
  { filters, metrics, generatedBy, rows }: ReportInput
) {
  // BOM so Excel opens the file as UTF-8.
  out.write("﻿");

  for (const [label, value] of summaryLines(filters, metrics, generatedBy)) {
    out.write(csvLine([label, value]));
  }

  out.write("\r\n");
  out.write(csvLine([...COLUMNS]));

  for await (const row of rows) {
    let ok = out.write(csvLine(cells(row)));

    const people = row.participants ?? [];

    if (people.length > 0) {
      out.write(csvLine(["", ...PARTICIPANT_HEADS]));

      for (const p of people) {
        ok = out.write(csvLine(["", ...participantCells(p)]));
      }
    }

    // Wait for the reader; a cancelled download closes the stream instead of
    // draining it, which must not leave this loop waiting forever.
    if (!ok && !out.destroyed) {
      await new Promise((resolve) => {
        out.once("drain", resolve);
        out.once("close", resolve);
      });
    }
  }

  out.end();
}

async function writeXlsx(
  out: PassThrough,
  { filters, metrics, generatedBy, rows }: ReportInput
) {
  const workbook = new ExcelJS.stream.xlsx.WorkbookWriter({
    stream: out,
    useStyles: true,
  });

  const summary = workbook.addWorksheet("Summary");

  summary.columns = [{ width: 26 }, { width: 44 }];

  for (const [label, value] of summaryLines(filters, metrics, generatedBy)) {
    summary.addRow([label, value]).getCell(1).font = { bold: true };
  }

  summary.commit();

  const sheet = workbook.addWorksheet("Bookings", {
    views: [{ state: "frozen", ySplit: 1 }],
  });

  sheet.columns = COLUMNS.map((header, i) => ({
    header,
    width: [11, 24, 32, 16, 18, 10, 36, 22, 13, 11, 11, 16, 24, 50][i],
  }));

  const header = sheet.getRow(1);

  header.font = { bold: true };
  header.commit();

  const safe = (values: (string | number)[]) =>
    values.map((c) => (typeof c === "string" ? neutralizeFormula(c) : c));

  for await (const row of rows) {
    // Text cells are written as plain strings (never formulas); the guard keeps
    // the same protection if a sheet is later exported to CSV.
    sheet.addRow(safe(cells(row))).commit();

    const people = row.participants ?? [];

    if (people.length === 0) continue;

    // Participants sit under their meeting as grouped rows (the outline
    // buttons collapse them), indented one column in.
    const head = sheet.addRow(["", ...PARTICIPANT_HEADS]);

    head.font = { bold: true, italic: true, color: { argb: "FF555555" } };
    head.outlineLevel = 1;
    head.commit();

    for (const p of people) {
      const line = sheet.addRow(["", ...safe(participantCells(p))]);

      line.outlineLevel = 1;
      line.commit();
    }
  }

  sheet.commit();

  await workbook.commit();
}

async function writePdf(
  out: PassThrough,
  { filters, metrics, generatedBy, rows }: ReportInput
) {
  const doc = new PDFDocument({ size: "A4", layout: "landscape", margin: 28 });

  doc.pipe(out);

  doc.fontSize(16).text("Meeting room booking report");
  doc.moveDown(0.5).fontSize(9);

  for (const [label, value] of summaryLines(filters, metrics, generatedBy)) {
    doc.text(`${label}: ${value}`);
  }

  doc.moveDown();

  const bookingWidths = [34, 100, 134, 74, 28, 140, 84, 58, 78, 54];
  // Participant lines start under the Organizer column (first column empty).
  const personWidths = [34, 150, 160, 90, 70];
  const pick = (r: ReportRow) => [
    String(r.bookingId),
    r.organizerName,
    r.organizerEmail,
    r.meetingType,
    r.priorityAtBooking === null ? "-" : String(r.priorityAtBooking),
    r.title,
    r.roomName,
    r.meetingDate,
    `${formatTime(r.startTime)} - ${formatTime(r.endTime)}`,
    r.bumped ? `${r.status} by ${r.bumped.byName}` : r.status,
  ];
  const heads = [
    "ID",
    "Organizer",
    "Email",
    "Type",
    "Pri",
    "Title",
    "Room",
    "Date",
    "Time",
    "Status",
  ];

  const drawRow = (values: string[], bold = false, widths = bookingWidths) => {
    const startY = doc.y;
    let x = doc.page.margins.left;
    let height = 0;

    doc.font(bold ? "Helvetica-Bold" : "Helvetica").fontSize(7);

    values.forEach((value, i) => {
      const h = doc.heightOfString(value, { width: widths[i] - 4 });

      height = Math.max(height, h);
    });

    if (startY + height > doc.page.height - doc.page.margins.bottom) {
      doc.addPage();
    }

    const y = doc.y;

    values.forEach((value, i) => {
      doc.text(value, x, y, { width: widths[i] - 4 });
      x += widths[i];
    });

    doc.x = doc.page.margins.left;
    doc.y = y + height + 3;
  };

  drawRow(heads, true);

  for await (const row of rows) {
    drawRow(pick(row));

    const people = row.participants ?? [];

    if (people.length === 0) continue;

    drawRow(["", ...PARTICIPANT_HEADS], true, personWidths);

    for (const p of people) {
      drawRow(["", ...participantCells(p)], false, personWidths);
    }

    // A little air between one meeting's block and the next.
    doc.y += 4;
  }

  doc.end();
}

export function reportFilename(
  filters: Pick<DashboardFilters, "period">,
  format: ReportFormat
) {
  const { start, end } = filters.period;

  return `booking-report_${start}${start === end ? "" : `_to_${end}`}.${format}`;
}

// Most bookings one report may contain (REPORT_MAX_ROWS overrides it). A
// larger selection is refused up front with a message, not cut off silently.
export const DEFAULT_REPORT_MAX_ROWS = 5000;

export function reportRowLimit(): number {
  const configured = Number(process.env.REPORT_MAX_ROWS);

  return Number.isInteger(configured) && configured > 0
    ? configured
    : DEFAULT_REPORT_MAX_ROWS;
}

export class ReportError extends Error {
  constructor(
    message: string,
    public status: number
  ) {
    super(message);
  }
}

type ReportOptions = {
  // Who downloads it, for the audit log (omitted only by tests).
  actorEmployeeId?: number;
  maxRows?: number;
};

// Checks the size, records the export, then starts generating the report and
// returns the byte stream immediately; the summary is computed first so the
// header matches the rows that follow.
export async function createReportStream(
  format: ReportFormat,
  filters: DashboardFilters,
  generatedBy: string,
  { actorEmployeeId, maxRows = reportRowLimit() }: ReportOptions = {}
): Promise<ReadableStream> {
  const metrics = await getDashboardMetrics(filters);

  if (metrics.totalBookings > maxRows) {
    throw new ReportError(
      `This report would contain ${metrics.totalBookings} bookings; at most ${maxRows} can be exported at once. Choose a shorter period or narrow the filters.`,
      422
    );
  }

  // Who exported what, before the first byte leaves (group_audit_logs is the
  // append-only log for administrative actions).
  await db.insert(groupAuditLogs).values({
    actorEmployeeId: actorEmployeeId ?? null,
    action: "REPORT_EXPORTED",
    details: {
      format,
      period: { mode: filters.period.mode, start: filters.period.start, end: filters.period.end },
      filters: {
        groupId: filters.groupId ?? null,
        roomId: filters.roomId ?? null,
        statusId: filters.statusId ?? null,
        search: filters.search ?? null,
        sort: filters.sort,
      },
      rows: metrics.totalBookings,
    },
  });

  const out = new PassThrough();

  renderReport(format, out, {
    filters,
    metrics,
    generatedBy,
    // Bookings added after the count are not let past the limit either.
    rows: take(iterateDashboardBookings(filters), maxRows, () => out.destroyed),
  });

  return Readable.toWeb(out) as ReadableStream;
}

// At most `max` rows, and none once `stopped()` - the download was cancelled
// or failed - so no more pages are read from the database for nobody.
async function* take<T>(rows: AsyncIterable<T>, max: number, stopped: () => boolean) {
  let count = 0;

  for await (const row of rows) {
    if (stopped() || count >= max) return;

    count++;
    yield row;
  }
}

// Writes the report to `out` in the background; a failure destroys the stream
// so the download aborts instead of ending as a truncated "complete" file.
export function renderReport(
  format: ReportFormat,
  out: PassThrough,
  input: ReportInput
) {
  const write =
    format === "csv" ? writeCsv : format === "xlsx" ? writeXlsx : writePdf;

  write(out, input).catch((error) => {
    // A cancelled download is not a failure worth logging.
    if (out.destroyed) return;

    console.error("Report generation failed:", error);
    out.destroy(error instanceof Error ? error : new Error("Report failed"));
  });
}
