import { PassThrough, Readable } from "node:stream";

import ExcelJS from "exceljs";
import PDFDocument from "pdfkit";

import { APP_TIMEZONE, invitationCategory } from "@/lib/constants";
import { neutralizeFormula } from "@/lib/spreadsheet-safe";
import { nowInAppTimezone } from "@/lib/time";

import {
  getDashboardMetrics,
  iterateDashboardBookings,
  iterateDashboardParticipants,
  type DashboardBookingBase,
  type DashboardFilters,
  type DashboardMetrics,
  type ParticipantExportRow,
} from "./booking-dashboard.service";
import type { BumpInfo } from "./bump-info.service";

// Report downloads for the booking dashboard. The same filters that drive the
// dashboard produce the file, rows are pulled from the database in batches and
// written straight to the response stream, so memory stays flat however many
// bookings match.

export type ReportFormat = "csv" | "xlsx" | "pdf";

export const REPORT_CONTENT_TYPES: Record<ReportFormat, string> = {
  csv: "text/csv; charset=utf-8",
  xlsx: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
  pdf: "application/pdf",
};

const COLUMNS = [
  "Booking ID",
  "Organizer name",
  "Organizer email",
  "Group",
  "Meeting type",
  "Priority",
  "Meeting title",
  "Room",
  "Date",
  "Start time",
  "End time",
  "Status",
  "Replaced by",
  "Replacement reason",
] as const;

const PARTICIPANT_COLUMNS = [
  "Booking ID",
  "Meeting title",
  "Date",
  "Start time",
  "End time",
  "Employee name",
  "Employee ID",
  "Email",
  "Invitation category",
  "Response",
] as const;

type ReportRow = DashboardBookingBase & { bumped?: BumpInfo | null };

const RESPONSE_TEXT: Record<string, string> = {
  ACCEPTED: "Accepted",
  DECLINED: "Declined",
  NO_RESPONSE: "No Response",
};

function participantCells(p: ParticipantExportRow): (string | number)[] {
  return [
    p.bookingId,
    p.title,
    p.meetingDate,
    p.startTime.slice(0, 5),
    p.endTime.slice(0, 5),
    p.name,
    p.employeeId,
    p.email,
    invitationCategory(p.isOptional),
    RESPONSE_TEXT[p.response] ?? "No Response",
  ];
}

function cells(r: ReportRow): (string | number)[] {
  return [
    r.bookingId,
    r.organizerName,
    r.organizerEmail,
    r.groupName ?? "",
    r.meetingType,
    r.priorityAtBooking ?? "",
    r.title,
    r.roomName,
    r.meetingDate,
    r.startTime.slice(0, 5),
    r.endTime.slice(0, 5),
    r.status,
    r.bumped?.byName ?? "",
    r.bumped?.reason ?? "",
  ];
}

function summaryLines(
  filters: Pick<DashboardFilters, "period">,
  metrics: DashboardMetrics,
  generatedBy: string
): [string, string | number][] {
  const now = nowInAppTimezone();

  return [
    ["Report generated", `${now.date} ${now.time.slice(0, 5)} (${APP_TIMEZONE})`],
    ["Generated by", generatedBy],
    ["Reporting period", filters.period.label],
    ["Total bookings", metrics.totalBookings],
    ["Confirmed bookings", metrics.confirmedBookings],
    ["Cancelled bookings", metrics.cancelledBookings],
    ["Replaced bookings", metrics.bumpedBookings],
    ["Total meeting hours", metrics.totalMeetingHours],
    ["Active meeting rooms", metrics.activeRooms],
  ];
}

function csvCell(value: string | number) {
  const text =
    typeof value === "string" ? neutralizeFormula(value) : String(value);

  return /[",\r\n]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text;
}

const csvLine = (values: (string | number)[]) =>
  values.map(csvCell).join(",") + "\r\n";

export type ReportInput = {
  filters: Pick<DashboardFilters, "period">;
  metrics: DashboardMetrics;
  generatedBy: string;
  rows: AsyncIterable<ReportRow>;
  // Every invited person of those bookings, one row each.
  participants: AsyncIterable<ParticipantExportRow>;
};

async function writeCsv(
  out: PassThrough,
  { filters, metrics, generatedBy, rows, participants }: ReportInput
) {
  // BOM so Excel opens the file as UTF-8.
  out.write("﻿");

  for (const [label, value] of summaryLines(filters, metrics, generatedBy)) {
    out.write(csvLine([label, value]));
  }

  out.write("\r\n");
  out.write(csvLine([...COLUMNS]));

  for await (const row of rows) {
    if (!out.write(csvLine(cells(row)))) {
      await new Promise((resolve) => out.once("drain", resolve));
    }
  }

  // Participants follow as a second table, one row per person.
  out.write("\r\n");
  out.write(csvLine(["Participants"]));
  out.write(csvLine([...PARTICIPANT_COLUMNS]));

  for await (const p of participants) {
    if (!out.write(csvLine(participantCells(p)))) {
      await new Promise((resolve) => out.once("drain", resolve));
    }
  }

  out.end();
}

async function writeXlsx(
  out: PassThrough,
  { filters, metrics, generatedBy, rows, participants }: ReportInput
) {
  const workbook = new ExcelJS.stream.xlsx.WorkbookWriter({
    stream: out,
    useStyles: true,
  });

  const summary = workbook.addWorksheet("Summary");

  summary.columns = [{ width: 26 }, { width: 44 }];

  for (const [label, value] of summaryLines(filters, metrics, generatedBy)) {
    summary.addRow([label, value]).getCell(1).font = { bold: true };
  }

  summary.commit();

  const sheet = workbook.addWorksheet("Bookings", {
    views: [{ state: "frozen", ySplit: 1 }],
  });

  sheet.columns = COLUMNS.map((header, i) => ({
    header,
    width: [11, 24, 32, 16, 18, 10, 36, 22, 13, 11, 11, 16, 24, 50][i],
  }));

  const header = sheet.getRow(1);

  header.font = { bold: true };
  header.commit();

  for await (const row of rows) {
    // Text cells are written as plain strings (never formulas); the guard keeps
    // the same protection if a sheet is later exported to CSV.
    sheet
      .addRow(cells(row).map((c) => (typeof c === "string" ? neutralizeFormula(c) : c)))
      .commit();
  }

  sheet.commit();

  // Participants live on their own sheet (one row per person), linked to the
  // bookings by Booking ID.
  const people = workbook.addWorksheet("Participants", {
    views: [{ state: "frozen", ySplit: 1 }],
  });

  people.columns = PARTICIPANT_COLUMNS.map((header, i) => ({
    header,
    width: [11, 36, 13, 11, 11, 24, 12, 34, 17, 14][i],
  }));

  const peopleHeader = people.getRow(1);

  peopleHeader.font = { bold: true };
  peopleHeader.commit();

  for await (const p of participants) {
    people
      .addRow(participantCells(p).map((c) => (typeof c === "string" ? neutralizeFormula(c) : c)))
      .commit();
  }

  people.commit();

  await workbook.commit();
}

async function writePdf(
  out: PassThrough,
  { filters, metrics, generatedBy, rows, participants }: ReportInput
) {
  const doc = new PDFDocument({ size: "A4", layout: "landscape", margin: 28 });

  doc.pipe(out);

  doc.fontSize(16).text("Meeting room booking report");
  doc.moveDown(0.5).fontSize(9);

  for (const [label, value] of summaryLines(filters, metrics, generatedBy)) {
    doc.text(`${label}: ${value}`);
  }

  doc.moveDown();

  const bookingWidths = [34, 100, 150, 74, 28, 140, 84, 58, 62, 54];
  const personWidths = [34, 170, 56, 80, 130, 190, 60, 64];
  const pick = (r: ReportRow) => [
    String(r.bookingId),
    r.organizerName,
    r.organizerEmail,
    r.meetingType,
    r.priorityAtBooking === null ? "-" : String(r.priorityAtBooking),
    r.title,
    r.roomName,
    r.meetingDate,
    `${r.startTime.slice(0, 5)}-${r.endTime.slice(0, 5)}`,
    r.bumped ? `${r.status} by ${r.bumped.byName}` : r.status,
  ];
  const heads = [
    "ID",
    "Organizer",
    "Email",
    "Type",
    "Pri",
    "Title",
    "Room",
    "Date",
    "Time",
    "Status",
  ];

  const drawRow = (values: string[], bold = false, widths = bookingWidths) => {
    const startY = doc.y;
    let x = doc.page.margins.left;
    let height = 0;

    doc.font(bold ? "Helvetica-Bold" : "Helvetica").fontSize(7);

    values.forEach((value, i) => {
      const h = doc.heightOfString(value, { width: widths[i] - 4 });

      height = Math.max(height, h);
    });

    if (startY + height > doc.page.height - doc.page.margins.bottom) {
      doc.addPage();
    }

    const y = doc.y;

    values.forEach((value, i) => {
      doc.text(value, x, y, { width: widths[i] - 4 });
      x += widths[i];
    });

    doc.x = doc.page.margins.left;
    doc.y = y + height + 3;
  };

  drawRow(heads, true);

  for await (const row of rows) {
    drawRow(pick(row));
  }

  // Participants: a separate table after the bookings, linked by Booking ID.
  doc.addPage();
  doc.font("Helvetica-Bold").fontSize(12).text("Participants");
  doc.moveDown(0.5);

  drawRow(
    ["ID", "Meeting", "Date", "Time", "Employee", "Email", "Category", "Response"],
    true,
    personWidths
  );

  for await (const p of participants) {
    drawRow(
      [
        String(p.bookingId),
        p.title,
        p.meetingDate,
        `${p.startTime.slice(0, 5)}-${p.endTime.slice(0, 5)}`,
        `${p.name} (ID ${p.employeeId})`,
        p.email,
        invitationCategory(p.isOptional),
        RESPONSE_TEXT[p.response] ?? "No Response",
      ],
      false,
      personWidths
    );
  }

  doc.end();
}

export function reportFilename(
  filters: Pick<DashboardFilters, "period">,
  format: ReportFormat
) {
  const { start, end } = filters.period;

  return `booking-report_${start}${start === end ? "" : `_to_${end}`}.${format}`;
}

// Starts generating the report and returns the byte stream immediately; the
// summary is computed first so the header matches the rows that follow.
export async function createReportStream(
  format: ReportFormat,
  filters: DashboardFilters,
  generatedBy: string
): Promise<ReadableStream> {
  const metrics = await getDashboardMetrics(filters);
  const out = new PassThrough();

  renderReport(format, out, {
    filters,
    metrics,
    generatedBy,
    rows: iterateDashboardBookings(filters),
    participants: iterateDashboardParticipants(filters),
  });

  return Readable.toWeb(out) as ReadableStream;
}

// Writes the report to `out` in the background; a failure destroys the stream
// so the download aborts instead of ending as a truncated "complete" file.
export function renderReport(
  format: ReportFormat,
  out: PassThrough,
  input: ReportInput
) {
  const write =
    format === "csv" ? writeCsv : format === "xlsx" ? writeXlsx : writePdf;

  write(out, input).catch((error) => {
    console.error("Report generation failed:", error);
    out.destroy(error instanceof Error ? error : new Error("Report failed"));
  });
}
